    }

    /** L, M, S at [ageDays] (linear between the weekly points, clamped to birth … 2 years). */
    fun lms(kind: GrowthKind, sex: BabySex, ageDays: Double): Triple<Double, Double, Double> {
        val t = table(kind, sex)
        val last = t.size / 3 - 1
        val pos = ageDays.coerceIn(0.0, MAX_DAYS.toDouble()) / STEP_DAYS
        val i = pos.toInt().coerceAtMost(last)
        val j = (i + 1).coerceAtMost(last)
        val f = pos - i
        fun at(k: Int): Double = t[i * 3 + k] + (t[j * 3 + k] - t[i * 3 + k]) * f
        return Triple(at(0), at(1), at(2))
    }

    /** The measurement at z-score [z] for this age. */
    fun valueAt(kind: GrowthKind, sex: BabySex, ageDays: Double, z: Double): Double {
        val (l, m, s) = lms(kind, sex, ageDays)
        return if (l == 0.0) m * exp(s * z) else m * (1 + l * s * z).pow(1 / l)
    }

    fun zScore(kind: GrowthKind, sex: BabySex, ageDays: Double, value: Double): Double {
        val (l, m, s) = lms(kind, sex, ageDays)
        return if (l == 0.0) ln(value / m) / s else ((value / m).pow(l) - 1) / (l * s)
    }

    /** Percentile (0–100) of [value] at this age. */
    fun percentile(kind: GrowthKind, sex: BabySex, ageDays: Double, value: Double): Double = normalCdf(zScore(kind, sex, ageDays, value)) * 100

    /** The curves drawn on WHO charts: percentile and its z-score. */
    val CURVES: List<Pair<Int, Double>> = listOf(3 to -1.881, 15 to -1.036, 50 to 0.0, 85 to 1.036, 97 to 1.881)

    private fun normalCdf(z: Double): Double {
        // Abramowitz–Stegun 7.1.26 (error < 1.5e-7)
        val x = abs(z) / sqrt(2.0)
        val t = 1 / (1 + 0.3275911 * x)
        val erf = 1 - ((((1.061405429 * t - 1.453152027) * t + 1.421413741) * t - 0.284496736) * t + 0.254829592) * t * exp(-x * x)
        return if (z >= 0) (1 + erf) / 2 else (1 - erf) / 2
    }
