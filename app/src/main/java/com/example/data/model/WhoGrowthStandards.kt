        GrowthKind.WEIGHT -> if (sex == BabySex.BOY) WEIGHT_BOYS else WEIGHT_GIRLS
        GrowthKind.LENGTH -> if (sex == BabySex.BOY) LENGTH_BOYS else LENGTH_GIRLS
